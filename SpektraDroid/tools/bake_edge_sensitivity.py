#!/usr/bin/env python3
"""Writes app/src/main/cpp/edge_sensitivity.inc: each film's spectral
sensitivity as the film's *edge* sees it -- nan_to_num(10 ** log_sensitivity),
no lens filter (engine/src/core/hanatos.cpp `film_sensitivity` with the bare
camera, as `Pipeline::build` makes `film_sensitivity_edge_`).

engine.bin carries the tc_lut built from the sensitivity but not the
sensitivity itself, and Film Edge needs it: the edge printer's light, the
spool fog and the date back's lamp are weighted per layer through it
(overscan.cpp `light_weights`). Baking it here keeps engine.bin's format.

    python3 SpektraDroid/tools/bake_edge_sensitivity.py
"""
import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "SpektraDroid/app/src/main/cpp/edge_sensitivity.inc"
DIRS = [ROOT / "engine/resources/profiles", ROOT / "engine/resources_product/profiles"]


def raw_profiles():
    out = {}
    for d in DIRS:
        for p in sorted(d.glob("*.json")):
            out[p.stem] = json.loads(p.read_text())
    return out


def resolve(name, raw, depth=0):
    """`derived_from` (spk_ref.py): a product profile is a delta on a base one."""
    assert depth < 8, "derived_from loop"
    d = raw[name]
    base = d.get("derived_from")
    if not base:
        return d
    b = resolve(base, raw, depth + 1)
    merged = {"info": {**b.get("info", {}), **d.get("info", {})},
              "data": {**b.get("data", {}), **d.get("data", {})}}
    merged["info"]["stock"] = d.get("info", {}).get("stock", name)
    return merged


def load(name, raw):
    d = resolve(name, raw)
    info, data = d.get("info", {}), d.get("data", {})
    if info.get("stage") != "filming":   # papers and print films are not cameras' films
        return None
    stock = info.get("stock") or name
    sens = data.get("log_sensitivity")
    wl = data.get("wavelengths")
    if not sens or not wl:
        return None
    rows = []
    for row in sens:
        vals = row if isinstance(row, list) else [row, row, row]
        out = []
        for v in vals:
            try:
                x = 10.0 ** float(v)
            except (TypeError, ValueError):
                x = 0.0
            out.append(0.0 if (x != x or math.isinf(x)) else x)
        rows.append(out)
    return stock, wl, rows


def lit(v):
    """A C++ float literal: 380 -> 380.0f, 1e-05 -> 1e-05f."""
    t = f"{v:.6g}"
    if "." not in t and "e" not in t and "inf" not in t and "nan" not in t:
        t += ".0"
    return t + "f"


def main():
    entries = {}
    wl_ref = None
    raw = raw_profiles()
    for name in sorted(raw):
        r = load(name, raw)
        if r is None:
            continue
        stock, wl, rows = r
        if wl_ref is None:
            wl_ref = wl
        if len(wl) != len(wl_ref) or any(abs(a - b) > 1e-6 for a, b in zip(wl, wl_ref)):
            print(f"skip {stock}: different wavelength grid")
            continue
        entries[stock] = rows
    lines = [
        "// Generated by SpektraDroid/tools/bake_edge_sensitivity.py -- do not edit.",
        "// Film spectral sensitivity, nan_to_num(10**log_sensitivity), (n_wl, 3) row-major.",
        f"constexpr int kEdgeSensWl = {len(wl_ref)};",
        f"constexpr float kEdgeSensWavelengths[{len(wl_ref)}] = {{"
        + ", ".join(lit(w) for w in wl_ref) + "};",
        "struct EdgeSens { const char* stock; float s[kEdgeSensWl * 3]; };",
        "constexpr EdgeSens kEdgeSens[] = {",
    ]
    for stock, rows in sorted(entries.items()):
        flat = ", ".join(lit(v) for row in rows for v in row)
        lines.append(f'    {{"{stock}", {{{flat}}}}},')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} films, {len(wl_ref)} wavelengths")


if __name__ == "__main__":
    main()
